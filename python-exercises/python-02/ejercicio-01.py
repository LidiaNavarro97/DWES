# Predice el tipo y el valor de estas expresiones 
# antes de comprobarlas en el intérprete: 

# 15 / 3 --> 5
print(15 / 3)

# 15 // 4 --> 3
print(15 // 4)

# 15 % 4 --> 3
print(15 % 4)

#  2 ** 3 --> 8
print(2 ** 3)

#  int("7") + 1 --> 8
print(int("7") + 1)

#  float("2.5") * 2 ->> 5
print(float("2.5") * 2)


